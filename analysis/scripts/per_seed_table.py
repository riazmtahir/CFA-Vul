#!/usr/bin/env python3
"""per_seed_table.py -- supplementary per-seed table of all 25 DiverseVul runs (final protocol).

Reads the per-seed result JSONs
  results/rq2_diversevul_final/    published, random_control, family_disjoint, seeds 1-3 (Stage B, 9 runs)
  results/rq2_diversevul_phase2/   project_disjoint 1-3, random_control 4-5, family_disjoint 4-5 (7 runs)
  results/rq2_diversevul_phase3/   commit_disjoint 1-3 (3 runs)
  results/rq2_diversevul_phase4b/  commit_decon, commit_sizectrl 1-3 (6 runs, H4b)
and writes
  paper/supplementary/per_seed_results.csv
  paper/supplementary/per_seed_results.tex   (standalone LaTeX document)
Every value is copied from the JSON (no rounding beyond 4 decimals in the .tex; full precision in the
.csv). Self-check: the per-arm means equal analysis/scripts/out/rq2_numbers.json and h4b_numbers.json,
otherwise exit 1. Usage (repository root): python analysis/scripts/per_seed_table.py
"""
from __future__ import annotations

import csv
import json
import os
import statistics as st
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.dirname(HERE)
ROOT = os.path.dirname(PAPER)
R = os.path.join(ROOT, "results")
RUNS = [("rq2_diversevul_final", "published", (1, 2, 3)),
        ("rq2_diversevul_final", "random_control", (1, 2, 3)),
        ("rq2_diversevul_phase2", "random_control", (4, 5)),
        ("rq2_diversevul_final", "family_disjoint", (1, 2, 3)),
        ("rq2_diversevul_phase2", "family_disjoint", (4, 5)),
        ("rq2_diversevul_phase2", "project_disjoint", (1, 2, 3)),
        ("rq2_diversevul_phase3", "commit_disjoint", (1, 2, 3)),
        ("rq2_diversevul_phase4b", "commit_decon", (1, 2, 3)),
        ("rq2_diversevul_phase4b", "commit_sizectrl", (1, 2, 3))]
LABEL = {"published": "Published", "random_control": "Random control", "family_disjoint": "Family-disjoint",
         "project_disjoint": "Project-disjoint", "commit_disjoint": "Commit-disjoint",
         "commit_decon": "Decontaminated (H4b)", "commit_sizectrl": "Matched stratified control (H4b)"}
GPU = {"rq2_diversevul_final": "RTX 4090", "rq2_diversevul_phase2": "RTX 4090 D",
       "rq2_diversevul_phase3": "RTX 4090 D", "rq2_diversevul_phase4b": "RTX 4090 D"}

rows = []
for d, arm, seeds in RUNS:
    for s in seeds:
        r = json.load(open(os.path.join(R, d, f"codebert-base_{arm}_seed{s}.json"), encoding="utf-8"))
        assert (r["arm"], r["seed"]) == (arm, s), (d, arm, s)
        t, fl = r["test"], r["length_only_floor"]["pr_auc"]
        rows.append({"arm": arm, "seed": s, "phase_dir": d, "gpu": GPU[d], "n_train": r["n_train"],
                     "n_valid": r["n_valid"], "n_test": t["n"], "test_pos_rate": t["positive_rate"],
                     "pr_auc": t["pr_auc"], "length_only_floor": fl, "headroom": t["pr_auc"] - fl,
                     "mcc": t["mcc"], "roc_auc": t["roc_auc"], "best_epoch": r["best_epoch"],
                     "epochs_run": r["epochs_run"], "lr": r["lr"], "patience": r["patience"],
                     "max_epochs": r["max_epochs"], "batch_size": r["batch_size"], "max_len": r["max_len"]})
assert len(rows) == 25, len(rows)
assert {(x["lr"], x["patience"], x["max_epochs"], x["batch_size"], x["max_len"]) for x in rows} == {(1e-5, 2, 15, 16, 512)}

# self-check against the paper's checkers
fails = []
num = json.load(open(os.path.join(HERE, "out", "rq2_numbers.json"), encoding="utf-8"))["per_arm"]
h4b = json.load(open(os.path.join(HERE, "out", "h4b_numbers.json"), encoding="utf-8"))["means"]
for arm in LABEL:
    m = st.mean(x["pr_auc"] for x in rows if x["arm"] == arm)
    want = num[arm]["pr_auc"]["mean"] if arm in num else h4b[arm]["pr_auc"]
    if abs(m - want) > 1e-9:
        fails.append((arm, m, want))

out = os.path.join(PAPER, "supplementary")
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "per_seed_results.csv"), "w", newline="", encoding="utf-8") as fh:
    w = csv.DictWriter(fh, fieldnames=list(rows[0]))
    w.writeheader()
    w.writerows(rows)

body = []
prev = None
for x in rows:
    lab = LABEL[x["arm"]] if x["arm"] != prev else ""
    prev = x["arm"]
    body.append(f"{lab} & {x['seed']} & {x['gpu']} & {x['n_train']:,} & {x['n_test']:,} & "
                f"{x['pr_auc']:.4f} & {x['length_only_floor']:.4f} & {x['headroom']:.4f} & {x['mcc']:.4f} & "
                f"{x['roc_auc']:.4f} & {x['best_epoch']}/{x['epochs_run']} \\\\")
tex = r"""\documentclass[10pt]{article}
\usepackage[margin=2cm,landscape]{geometry}
\usepackage{booktabs}
\begin{document}
\section*{Supplementary Table S1: per-seed results of all 25 DiverseVul runs}
CodeBERT, final protocol (learning rate $10^{-5}$, at most 15 epochs, patience 2, batch 16, 512 tokens).
Test metrics of the epoch selected on validation PR-AUC. Headroom = PR-AUC $-$ length-only floor.
MCC at the test-set max-F1 threshold. Epochs: best epoch / epochs run. Generated by
\texttt{analysis/scripts/per\_seed\_table.py} from the result JSONs; the same values with full precision are in
\texttt{per\_seed\_results.csv}.

\medskip
\begin{tabular}{lrlrrrrrrrr}
\toprule
Arm & Seed & GPU & Train & Test & PR-AUC & Floor & Headroom & MCC & ROC-AUC & Epochs \\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\end{document}
"""
open(os.path.join(out, "per_seed_results.tex"), "w", encoding="utf-8", newline="\n").write(tex)
# fragment (table only) for supplementary/supplementary.tex
frag = tex[tex.index(r"\section*{"):tex.index(r"\end{document}")]
open(os.path.join(out, "per_seed_results_fragment.tex"), "w", encoding="utf-8", newline="\n").write(frag)
print(f"wrote supplementary/per_seed_results.{{csv,tex}}: {len(rows)} runs; mean check "
      + ("passed" if not fails else f"FAILED {fails}"))
sys.exit(1 if fails else 0)
