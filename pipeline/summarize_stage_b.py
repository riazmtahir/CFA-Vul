"""Stage B summary: per-run table, per-arm mean ± std, and paired Δ by seed.

Reads only the result JSONs in rq2_diversevul_final/ and writes
stage_b_summary.md next to them. Never touches checkpoints or data.

    python summarize_stage_b.py            # print + write stage_b_summary.md
    python summarize_stage_b.py --quiet    # print the short table only (status.sh)

std is the sample std (n-1). PR/pos is PR-AUC divided by the test positive rate,
because each arm has its own test set and PR-AUC scales with prevalence.
"""
import argparse
import glob
import json
import os
import statistics as st

ARMS = ["published", "random_control", "family_disjoint"]


def mean_std(xs):
    if not xs:
        return "—"
    if len(xs) == 1:
        return f"{xs[0]:.4f} (n=1)"
    return f"{st.mean(xs):.4f} ± {st.stdev(xs):.4f} (n={len(xs)})"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=os.path.join(os.environ.get("CFA_DATA_DIR", "data"), "rq2_diversevul_final"))
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    runs = []
    for f in sorted(glob.glob(os.path.join(args.dir, "*.json"))):
        r = json.load(open(f))
        if "test" not in r:
            continue
        t = r["test"]
        runs.append({
            "arm": r["arm"], "seed": r["seed"], "pr": t["pr_auc"], "roc": t["roc_auc"],
            "mcc": t["mcc"], "pos": t["positive_rate"], "n": t["n"],
            "floor": (r.get("length_only_floor") or {}).get("pr_auc"),
            "worst": (r.get("worst_family") or {}).get("worst_family_pr_auc"),
            "best_ep": r.get("best_epoch"), "ep_run": r.get("epochs_run"),
            "hours": r.get("runtime_seconds", 0) / 3600,
        })
    if not runs:
        raise SystemExit(1)

    runs.sort(key=lambda x: (x["seed"], ARMS.index(x["arm"]) if x["arm"] in ARMS else 9))
    lines = ["| arm | seed | PR-AUC | ROC-AUC | MCC | PR/pos | floor | worst-fam | best/run ep | h |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for x in runs:
        lines.append(f"| {x['arm']} | {x['seed']} | {x['pr']:.4f} | {x['roc']:.4f} | {x['mcc']:.4f} | "
                     f"{x['pr'] / x['pos']:.2f} | {x['floor']} | {x['worst']} | "
                     f"{x['best_ep']}/{x['ep_run']} | {x['hours']:.1f} |")

    by = {a: {x["seed"]: x for x in runs if x["arm"] == a} for a in ARMS}
    agg = ["| arm | PR-AUC | PR/pos | ROC-AUC |", "|---|---|---|---|"]
    for a in ARMS:
        xs = list(by[a].values())
        agg.append(f"| {a} | {mean_std([x['pr'] for x in xs])} | "
                   f"{mean_std([x['pr'] / x['pos'] for x in xs])} | {mean_std([x['roc'] for x in xs])} |")

    deltas = ["| Δ (paired by seed) | per-seed PR-AUC Δ | mean Δ |", "|---|---|---|"]
    for lo, hi in [("published", "random_control"), ("random_control", "family_disjoint")]:
        seeds = sorted(set(by[lo]) & set(by[hi]))
        d = [by[hi][s]["pr"] - by[lo][s]["pr"] for s in seeds]
        per = ", ".join(f"s{s} {v:+.4f}" for s, v in zip(seeds, d)) or "—"
        deltas.append(f"| {lo} → {hi} | {per} | {mean_std(d) if d else '—'} |")

    done = len(runs)
    hours = [x["hours"] for x in runs]
    eta = f"{done}/9 runs done; avg {st.mean(hours):.1f} h/run; ~{st.mean(hours) * (9 - done):.0f} h left" \
        if done < 9 else "9/9 runs done"

    print(eta)
    print("\n".join(lines))
    print()
    print("\n".join(agg))
    print()
    print("\n".join(deltas))
    if args.quiet:
        return

    md = ["# Stage B — DiverseVul final (CodeBERT, class-weighted, lr 1e-5, ≤15 ep, patience 2)", "",
          f"_{eta}. Generated by summarize_stage_b.py from the result JSONs; do not edit by hand._", "",
          "## Runs", *lines, "", "## Per arm (sample std)", *agg, "", "## Δ", *deltas, ""]
    out = os.path.join(args.dir, "stage_b_summary.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(md))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
